"""Package the Qu's retained original art into native mipmapped DDS textures."""
from PIL import Image, ImageChops, ImageDraw, ImageFilter, ImageOps

from build_art import ROOT, SIZES, dds, leader_cell

ART = ROOT / 'TheQu/Art'
PREFIX = 'CWC3_Qu_'
PORTRAITS = ('Civ', 'Leader', 'Harvester', 'Foundry')
SCENES = {'Dawn': (1024, 768), 'Diplomacy': (1600, 1200), 'Map': (360, 412)}
RESAMPLE = Image.Resampling.LANCZOS


def icon(image, inset=0):
    image = ImageOps.fit(image, (1024, 1024), RESAMPLE).convert('RGBA')
    if inset:
        size = 1024 - 2 * inset
        artwork = image.resize((size, size), RESAMPLE)
        paper = Image.new('RGBA', image.size, image.getpixel((0, 0)))
        feather = Image.new('L', artwork.size)
        ImageDraw.Draw(feather).rectangle((12, 12, size - 13, size - 13), fill=255)
        paper.paste(artwork, (inset, inset), feather.filter(ImageFilter.GaussianBlur(5)))
        image = paper
    mask = Image.new('L', image.size)
    border = (24, 24, 999, 999)
    ImageDraw.Draw(mask).ellipse(border, fill=255)
    image.putalpha(mask)
    ImageDraw.Draw(image).ellipse(border, outline=(155, 152, 143, 255), width=21)
    return image


def heraldry(emblem):
    rgb = ImageOps.fit(emblem, (1024, 1024), RESAMPLE).convert('RGB')
    red, green, _ = rgb.split()
    strength = ImageChops.darker(red, green)
    mask = strength.point(lambda value: max(0, min(255, (value - 75) * 5)))
    result = Image.new('RGBA', mask.size, 'white')
    result.putalpha(mask)
    return result


def compile_art():
    sources = {name: Image.open(ART / 'Sources' / f'{name}.png')
               for name in (*PORTRAITS, 'Dawn', 'Diplomacy')}
    alpha = heraldry(sources['Civ'])
    insets = {'Civ': 80, 'Leader': 112, 'Harvester': 112}
    icons = {name: icon(sources[name], inset=insets.get(name, 0)) for name in PORTRAITS}
    icons['Unit'] = icons.pop('Harvester')
    icons['Alpha'] = alpha
    icons['Flag'] = alpha.rotate(-16, Image.Resampling.BICUBIC)
    declarations = []
    for name, master in icons.items():
        for size in ((32,) if name == 'Flag' else SIZES):
            filename = f'{PREFIX}{name}{size}.dds'
            dds(leader_cell(master,size) if name=='Leader' else master.resize((size, size), RESAMPLE), ART / filename)
            declarations.append(f" ('CWC3_QU_{name.upper()}_ATLAS',{size},'{filename}',1,1)")
    for name, dimensions in SCENES.items():
        source = sources['Dawn' if name == 'Map' else name]
        scene = ImageOps.fit(source, dimensions, RESAMPLE)
        dds(scene, ART / f'{PREFIX}{name}.dds', mipmaps=False)
    (ART / f'{PREFIX}LeaderScene.xml').write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<LeaderScene FallbackImage="CWC3_Qu_Diplomacy.dds" />\n', encoding='utf-8', newline='\n')
    (ROOT / 'TheQu/SQL/Qu_Art.sql').write_text(
        '-- Generated by tools/build_qu_art.py.\n'
        'INSERT INTO IconTextureAtlases(Atlas,IconSize,Filename,IconsPerRow,IconsPerColumn) VALUES\n'
        + ',\n'.join(declarations) + ';\n', encoding='utf-8', newline='\n')


if __name__ == '__main__':
    compile_art()
