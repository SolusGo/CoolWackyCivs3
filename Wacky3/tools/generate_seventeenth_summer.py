"""Generate Summer registration and active CP151 Spearman/Granary clones."""
import os
from pathlib import Path
from baseline import ROOT
from target_schema import schema_database
from generate_hollow_choir import clone, companions, literal

SQL = Path(os.environ.get('CWC3_SQL_ROOT', ROOT))/'TheSeventeenthSummer/SQL'
CIV = 'CIVILIZATION_CWC3_SEVENTEENTH_SUMMER'
LEADER = 'LEADER_CWC3_IXA'
UNIT = 'UNIT_CWC3_SHELLGUARD'
NURSERY = 'BUILDING_CWC3_BROOD_NURSERY'
LINEAGE = 'PROMOTION_SUMMER_BROOD_LINEAGE'
AWAKENED = 'PROMOTION_SUMMER_AWAKENED'
PREFIX = 'TXT_KEY_CWC3_SUMMER_'
DUMMIES = [('DORMANT_FOOD','FOOD',1), ('EMERGENCE_PRODUCTION','PRODUCTION',2),
           ('EMERGENCE_CULTURE','CULTURE',1), ('NURSERY_PRODUCTION','PRODUCTION',1)]


def write(kind, content):
    SQL.mkdir(parents=True, exist_ok=True)
    (SQL/f'Summer_{kind}.sql').write_text(
        '-- Generated by tools/generate_seventeenth_summer.py.\n'+content.replace('CWC3_Choir', 'CWC3_Summer'),
        encoding='utf-8', newline='\n')


def main():
    db = schema_database()
    civ = """INSERT INTO Colors(Type,Red,Green,Blue,Alpha) VALUES
 ('COLOR_CWC3_SUMMER_AMBER',0.85,0.53,0.12,1),('COLOR_CWC3_SUMMER_ROOT',0.18,0.12,0.06,1);
INSERT INTO PlayerColors(Type,PrimaryColor,SecondaryColor,TextColor) VALUES
 ('PLAYERCOLOR_CWC3_SUMMER','COLOR_CWC3_SUMMER_AMBER','COLOR_CWC3_SUMMER_ROOT','COLOR_PLAYER_WHITE_TEXT');
INSERT INTO Traits(Type,Description,ShortDescription) VALUES
 ('TRAIT_CWC3_GREAT_EMERGENCE','TXT_KEY_CWC3_SUMMER_TRAIT_HELP','TXT_KEY_CWC3_SUMMER_TRAIT');
"""
    civ += clone('Civilizations', 'CIVILIZATION_AMERICA', CIV, dict(
        Description=PREFIX+'CIV', ShortDescription=PREFIX+'SHORT', Adjective=PREFIX+'ADJECTIVE',
        Civilopedia=PREFIX+'CIV_PEDIA', CivilopediaTag=PREFIX+'CIV5', Strategy=PREFIX+'STRATEGY',
        DefaultPlayerColor='PLAYERCOLOR_CWC3_SUMMER', Playable=1, AIPlayable=0, PackageID=None,
        DawnOfManQuote=PREFIX+'DAWN', DawnOfManAudio=''))
    civ += clone('Leaders', 'LEADER_WASHINGTON', LEADER, dict(
        Description=PREFIX+'LEADER', Civilopedia=PREFIX+'LEADER_PEDIA', CivilopediaTag=PREFIX+'IXA',
        PackageID=None, Boldness=3, WarmongerHate=6, Loyalty=8, WonderCompetitiveness=7))
    for table in ['Civilization_FreeBuildingClasses', 'Civilization_FreeTechs', 'Civilization_FreeUnits']:
        civ += f"""CREATE TEMP TABLE CWC3_SummerStart AS SELECT * FROM {table} WHERE CivilizationType='CIVILIZATION_AMERICA';
UPDATE CWC3_SummerStart SET CivilizationType='{CIV}';
INSERT INTO {table} SELECT * FROM CWC3_SummerStart;
DROP TABLE CWC3_SummerStart;
"""
    civ += f"""INSERT INTO Civilization_Leaders VALUES ('{CIV}','{LEADER}');
INSERT INTO Leader_Traits VALUES ('{LEADER}','TRAIT_CWC3_GREAT_EMERGENCE');
INSERT INTO Civilization_UnitClassOverrides(CivilizationType,UnitClassType,UnitType) VALUES ('{CIV}','UNITCLASS_SPEARMAN','{UNIT}');
INSERT INTO Civilization_BuildingClassOverrides(CivilizationType,BuildingClassType,BuildingType) VALUES ('{CIV}','BUILDINGCLASS_GRANARY','{NURSERY}');
INSERT INTO Leader_Flavors(LeaderType,FlavorType,Flavor)
 SELECT '{LEADER}',Type,CASE Type WHEN 'FLAVOR_SCIENCE' THEN 8 WHEN 'FLAVOR_CULTURE' THEN 8
 WHEN 'FLAVOR_GROWTH' THEN 8 WHEN 'FLAVOR_DEFENSE' THEN 7 ELSE 5 END FROM Flavors;
INSERT INTO Leader_MajorCivApproachBiases(LeaderType,MajorCivApproachType,Bias)
 SELECT '{LEADER}',Type,CASE Type WHEN 'MAJOR_CIV_APPROACH_WAR' THEN 3 WHEN 'MAJOR_CIV_APPROACH_FRIENDLY' THEN 7 ELSE 5 END FROM MajorCivApproachTypes;
INSERT INTO Leader_MinorCivApproachBiases(LeaderType,MinorCivApproachType,Bias)
 SELECT '{LEADER}',Type,5 FROM MinorCivApproachTypes;
CREATE TABLE CWC3_SummerCycles(GameSpeedType TEXT PRIMARY KEY, Dormancy INTEGER NOT NULL, Emergence INTEGER NOT NULL);
INSERT INTO CWC3_SummerCycles VALUES ('GAMESPEED_QUICK',9,3),('GAMESPEED_STANDARD',13,4),('GAMESPEED_EPIC',20,6),('GAMESPEED_MARATHON',39,12);
"""
    cities = ['First Emergence','Amber Root','Seventeen Rings','Golden Canopy','Deep Brood','Patient Earth',
              'Chorus Grove','The Waiting Chamber','Translucent Dawn','Rootbound Throne','Summer Vault',
              'Second Song','Resin Gate','Hushed Orchard','Wingfall','Sunward Hollow','Eternal Return','Last Echo']
    spies = ['Trill','Instar','Resin','Husk','Rootwhisper','Amber','Ring','Canopy','Chirp','Molt']
    for table, names, key in [('Civilization_CityNames', cities, 'CITY'), ('Civilization_SpyNames', spies, 'SPY')]:
        for i in range(1,len(names)+1):
            civ += f"INSERT INTO {table} VALUES ('{CIV}','{PREFIX}{key}_{i}');\n"
    write('Civilization', civ)
    unit = clone('Units','UNIT_SPEARMAN',UNIT,dict(Description=PREFIX+'UNIT', Civilopedia=PREFIX+'UNIT_PEDIA',
                 Help=PREFIX+'UNIT_HELP', Strategy=PREFIX+'UNIT_HELP'))
    unit += f"UPDATE Units SET BaseSightRange=BaseSightRange+1 WHERE Type='{UNIT}';\n"
    unit += companions(db,'Unit_','UnitType','UNIT_SPEARMAN',UNIT)
    unit += f"""-- Identity has no combat or sight effects, and survives every ordinary upgrade.
INSERT INTO UnitPromotions(Type,Description,Help,CannotBeChosen,LostWithUpgrade,ShowInUnitPanel,IsVisibleAboveFlag,PortraitIndex,IconAtlas)
 VALUES ('{LINEAGE}','{PREFIX}LINEAGE','{PREFIX}LINEAGE_HELP',1,0,0,0,9,'ABILITY_ATLAS');
-- CombatPercent enters both melee attack/defense and ranged strength in CP151.
INSERT INTO UnitPromotions(Type,Description,Help,CannotBeChosen,LostWithUpgrade,LostOnGifting,CombatPercent,PortraitIndex,IconAtlas)
 VALUES ('{AWAKENED}','{PREFIX}AWAKENED','{PREFIX}AWAKENED_HELP',1,1,1,20,9,'ABILITY_ATLAS');
INSERT INTO Unit_FreePromotions(UnitType,PromotionType) VALUES ('{UNIT}','{LINEAGE}');
"""
    write('Units',unit)
    building = clone('Buildings','BUILDING_GRANARY',NURSERY,dict(Description=PREFIX+'NURSERY',
                     Civilopedia=PREFIX+'NURSERY_PEDIA',Help=PREFIX+'NURSERY_HELP',Strategy=PREFIX+'NURSERY_HELP'))
    building += companions(db,'Building_','BuildingType','BUILDING_GRANARY',NURSERY)
    building += f"""UPDATE Building_YieldChanges SET Yield=Yield+1 WHERE BuildingType='{NURSERY}' AND YieldType='YIELD_FAITH';
INSERT INTO Building_YieldChanges(BuildingType,YieldType,Yield)
 SELECT '{NURSERY}','YIELD_FAITH',1 WHERE NOT EXISTS
 (SELECT 1 FROM Building_YieldChanges WHERE BuildingType='{NURSERY}' AND YieldType='YIELD_FAITH');
"""
    for suffix,kind,amount in DUMMIES:
        typ, cls = 'BUILDING_SUMMER_'+suffix, 'BUILDINGCLASS_CWC3_SUMMER_'+suffix
        building += f"""INSERT INTO BuildingClasses(Type,DefaultBuilding,Description) VALUES ('{cls}','{typ}','{PREFIX}DUMMY');
INSERT INTO Buildings(Type,BuildingClass,Description,Help,Cost,FaithCost,GoldMaintenance,GreatWorkCount,NeverCapture,NukeImmune,IsDummy,ShowInPedia,ConquestProb,IconAtlas,PortraitIndex)
 VALUES ('{typ}','{cls}','{PREFIX}DUMMY','{PREFIX}DUMMY_HELP',-1,-1,0,-1,1,1,1,0,0,'CIV_COLOR_ATLAS',0);
INSERT INTO Building_YieldChanges(BuildingType,YieldType,Yield) VALUES ('{typ}','YIELD_{kind}',{amount});
"""
    write('Buildings',building)
    timing = ('The first processed owner-turn is Dormancy turn 1. Phase changes occur after that turn\'s economic collection, '
              'apply immediately to combat, and schedule city yields for the next economic payout. '
              'At Standard speed, owner-turns 1-13 are Dormancy, 14-17 Emergence, 18-30 Dormancy, and 31-34 Emergence. '
              'Quick: 9/3; Standard: 13/4; Epic: 20/6; Marathon: 39/12 (Dormancy/Emergence).')
    text = dict(CIV='The Seventeenth Summer',SHORT='Seventeenth Summer',ADJECTIVE='Summer',LEADER='Chorus-Mother Ixa',
        TRAIT='The Great Emergence',
        TRAIT_HELP='Repeat Dormancy (+1 [ICON_FOOD] Food per city) and Emergence (+2 [ICON_PRODUCTION] Production and +1 [ICON_CULTURE] Culture per city). '+timing,
        CIV_PEDIA='We Were Never Gone. Intelligent cicada-like people sleep beneath the roots, preserving their memories in tree rings and amber. Their synchronized return fills the summer canopy with a chorus of discovery and creation. '+timing,
        LEADER_PEDIA='Chorus-Mother Ixa is a regal cicada queen with translucent golden wings and tree-ring markings. She rules from an amber-and-root throne beneath the earth, measuring the histories of surface empires in the patient intervals between summers.',
        STRATEGY='Favor Science and Culture. Grow during Dormancy; time production and military campaigns for Emergence. Build Brood Nurseries and preserve Shellguard veterans. '+timing,
        UNIT='Shellguard',UNIT_HELP='Replaces the active Spearman with +1 Sight. All other baseline properties and companion effects are inherited. Shellguards and their upgraded descendants receive +20% Combat Strength attacking and defending during Emergence while owned by a human Seventeenth Summer player. Brood lineage survives multiple upgrades; ordinary Spearmen never gain it. Extra Sight belongs to the Shellguard unit type.',
        UNIT_PEDIA='Armored in the memory of old shells, these watchful soldiers guard the brood through the quiet years. Their descendants answer the chorus when the summer returns.',
        NURSERY='Brood Nursery',NURSERY_HELP='Replaces the active Granary and preserves its normal effects. Adds +1 [ICON_PEACE] Faith permanently, plus +1 [ICON_PRODUCTION] Production during Emergence under eligible Summer ownership. With the UA, unique bonuses total +1 Food and +1 Faith in Dormancy, or +3 Production, +1 Culture and +1 Faith in Emergence. Phase yields apply to the next payout.',
        NURSERY_PEDIA='Under branching roots, the next generation grows in chambers warm with amber light. When the chorus sounds, quiet care becomes a burst of shared labor.',
        LINEAGE='Brood Lineage',LINEAGE_HELP='Internal permanent Shellguard ancestry marker. Cannot be selected; survives upgrades. No independent yield or combat effect.',
        AWAKENED='Awakened',AWAKENED_HELP='+20% Combat Strength attacking and defending during Emergence. Requires Shellguard lineage and eligible Summer ownership.',
        DUMMY='Summer Cycle',DUMMY_HELP='Invisible internal zero/one phase yield controller. Cannot be constructed or purchased.',
        EMERGENCE_TITLE='The Great Emergence',EMERGENCE_NOTICE='We Were Never Gone. Emergence begins: +2 Production and +1 Culture per city, +1 Production per Brood Nursery, and +20% Combat Strength for brood veterans. City bonuses apply to the next economic payout.',
        DORMANCY_TITLE='Beneath the Roots',DORMANCY_NOTICE='The chorus returns to Dormancy: +1 Food per city; Awakened and Emergence Production/Culture end. City bonuses apply to the next economic payout.',
        GREETING_1='Another visitor from the surface? How curious. Tell me, little one... how many summers have passed since we last spoke?',
        WAR_1='We have waited seventeen summers for this moment. You shall not make us wait another.',
        ATTACKED_1='You have chosen an unfortunate season.',DEFEAT_1='Our voices fade... but beneath the earth... another generation waits.',
        FALLBACK_1='Beneath the earth, we remember. Let your words join the chorus.',
        DAWN='Chorus-Mother Ixa, the roots stir beneath your amber throne. Your golden wings remember the light, and your people await the seventeenth summer. Grow through the quiet years, build halls for the brood, and let your emergence fill the world with knowledge and song. We Were Never Gone.')
    for key,names in [('CITY',cities),('SPY',spies)]:
        for i,name in enumerate(names,1): text[f'{key}_{i}']=name
    text.update(CIV5_HEADING_1='We Were Never Gone',CIV5_TEXT_1=text['CIV_PEDIA'],CIV5_HEADING_2=text['TRAIT'],
        CIV5_TEXT_2=text['TRAIT_HELP'],CIV5_FACTOID_HEADING='Seventeen Summers',CIV5_FACTOID_TEXT='The Standard cycle lasts seventeen owner-turns.',
        IXA_NAME=text['LEADER'],IXA_SUBTITLE='Mother of the Returning Chorus',IXA_LIVED='Fictional cicada civilization',
        IXA_TITLES_1='Chorus-Mother',IXA_HEADING_1='The Amber Throne',IXA_TEXT_1=text['LEADER_PEDIA'],IXA_FACT_1='Ixa measures time in the rings of sleeping trees.')
    localization='INSERT INTO Language_en_US(Tag,Text) VALUES\n'+',\n'.join(
        ' ('+literal(PREFIX+k)+','+literal(v)+')' for k,v in text.items())+';\n'
    for response,tag in [('FIRST_GREETING','GREETING'),('DECLAREWAR','WAR'),('ATTACKED','ATTACKED'),('DEFEATED','DEFEAT')]:
        localization += f"INSERT INTO Diplomacy_Responses(LeaderType,ResponseType,Response,Bias) VALUES ('{LEADER}','RESPONSE_{response}','{PREFIX}{tag}_%',1);\n"
    localization += f"""INSERT INTO Diplomacy_Responses(LeaderType,ResponseType,Response,Bias)
 SELECT DISTINCT '{LEADER}',Native.ResponseType,'{PREFIX}FALLBACK_%',1 FROM Diplomacy_Responses AS Native
 WHERE Native.LeaderType='LEADER_WASHINGTON' AND NOT EXISTS
 (SELECT 1 FROM Diplomacy_Responses AS Summer WHERE Summer.LeaderType='{LEADER}' AND Summer.ResponseType=Native.ResponseType);
"""
    write('Text',localization)
    db.close()
    print('Generated Summer registration, active Spearman/Granary inheritance, four controllers and localization')


if __name__ == '__main__': main()
