def literal(value):
    if value is None: return 'NULL'
    if isinstance(value, int): return str(value)
    return "'"+str(value).replace("'", "''")+"'"


def clone(table, old, new, changes):
    changes = {'ID': None, 'Type': new, **changes}
    return (f'CREATE TEMP TABLE CWC3_ChoirClone AS SELECT * FROM {quote(table)} WHERE Type={literal(old)};\n'
            +'UPDATE CWC3_ChoirClone SET '+','.join(quote(k)+'='+literal(v) for k,v in changes.items())+';\n'
            +f'INSERT INTO {quote(table)} SELECT * FROM CWC3_ChoirClone;\nDROP TABLE CWC3_ChoirClone;\n')


def companions(db, prefix, column, old, new):
    result = ''
    for table in approved_companions(prefix, column):
        columns = [r[1] for r in db.execute('PRAGMA table_info('+quote(table)+')')]
        if column not in columns: continue
        assignments = quote(column)+'='+literal(new)
        if 'ID' in columns: assignments += ',ID=NULL'
        result += (f'CREATE TEMP TABLE CWC3_ChoirCompanion AS SELECT * FROM {quote(table)} WHERE {quote(column)}={literal(old)};\n'
                   +f'UPDATE CWC3_ChoirCompanion SET {assignments};\nINSERT INTO {quote(table)} SELECT * FROM CWC3_ChoirCompanion;\nDROP TABLE CWC3_ChoirCompanion;\n')
    return result


def write(name, content):
    SQL.mkdir(parents=True, exist_ok=True)
    (SQL/f'Choir_{name}.sql').write_text('-- Generated by tools/generate_hollow_choir.py.\n'+content, encoding='utf-8', newline='\n')


