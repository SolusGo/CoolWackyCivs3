"""Compile retained PALEO PNG masters to legacy BGRA8888 DDS, with icon mips."""
import math
from PIL import Image, ImageDraw, ImageOps
from baseline import ROOT
from build_art import dds, SIZES

ART = ROOT/'ThePaleontologicalDirectorate/Art'


def circle(image, centering=(.5,.5)):
    image = ImageOps.fit(image,(1024,1024),Image.Resampling.LANCZOS,centering=centering).convert('RGBA')
    mask = Image.new('L',image.size)
    ImageDraw.Draw(mask).ellipse((30,30,994,994),fill=255)
    image.putalpha(mask)
    ImageDraw.Draw(image).ellipse((30,30,994,994),outline=(219,175,77,255),width=18)
    return image


def main():
    sources = {n:Image.open(ART/'Sources'/f'{n}.png').convert('RGBA') for n in ['Leader','Emblem','Unit','Museum']}
    # Code-native white ammonite glyph for the alpha atlas and unit flag.
    alpha = Image.new('RGBA',(1024,1024)); draw = ImageDraw.Draw(alpha)
    points = []
    for i in range(401):
        angle = i / 400 * math.pi * 4.8
        radius = 38 + 355 * i / 400
        points.append((512+math.cos(angle)*radius,512+math.sin(angle)*radius))
    draw.line(points,fill='white',width=65,joint='curve')
    for i in range(200,401,15):
        angle = i / 400 * math.pi * 4.8
        radius = 38 + 355 * i / 400
        draw.line([(512+math.cos(angle)*radius,512+math.sin(angle)*radius),
                   (512+math.cos(angle+.06)*(radius-80),512+math.sin(angle+.06)*(radius-80))],fill='white',width=22)
    alpha.save(ART/'Sources/Alpha.png')
    masters = {'Civ':sources['Emblem'], 'Leader':circle(sources['Leader'],(.45,.25)),
               'Unit':circle(sources['Unit']), 'Museum':circle(sources['Museum']), 'Alpha':alpha, 'Flag':alpha}
    declarations = []
    for kind, master in masters.items():
        for size in SIZES:
            name = f'PALEO_{kind}{size}.dds'
            dds(ImageOps.fit(master,(size,size),Image.Resampling.LANCZOS),ART/name)
            declarations.append(f" ('PALEO_{kind.upper()}_ATLAS',{size},'{name}',1,1)")
    dds(ImageOps.fit(sources['Leader'],(1600,1200),Image.Resampling.LANCZOS),ART/'PALEO_Leader.dds',False)
    dds(ImageOps.fit(sources['Leader'],(1024,768),Image.Resampling.LANCZOS),ART/'PALEO_Dawn.dds',False)
    dds(ImageOps.fit(sources['Museum'],(360,412),Image.Resampling.LANCZOS),ART/'PALEO_Map.dds',False)
    (ART/'PALEO_LeaderScene.xml').write_text('<?xml version="1.0" encoding="utf-8"?>\n<LeaderScene FallbackImage="PALEO_Leader.dds" />\n',encoding='utf-8',newline='\n')
    (ROOT/'ThePaleontologicalDirectorate/SQL/PALEO_Art.sql').write_text(
        '-- Generated by tools/build_paleo_art.py.\nINSERT INTO IconTextureAtlases(Atlas,IconSize,Filename,IconsPerRow,IconsPerColumn) VALUES\n'
        +',\n'.join(declarations)+';\n',encoding='utf-8',newline='\n')
    review = Image.new('RGB',(1280,650),(30,22,15)); draw = ImageDraw.Draw(review)
    for i,kind in enumerate(['Civ','Leader','Unit','Museum','Alpha']):
        icon = Image.open(ART/f'PALEO_{kind}256.dds')
        review.paste(icon,(i*256,25),icon); draw.text((i*256+10,5),kind,fill='white')
    scene = Image.open(ART/'PALEO_Leader.dds'); scene.thumbnail((490,350)); review.paste(scene,(20,290))
    scene = Image.open(ART/'PALEO_Map.dds'); scene.thumbnail((290,350)); review.paste(scene,(570,290))
    review.save(ART/'Sources/ArtReview.png')
    print('Compiled PALEO: 57 DDS assets, original portraits, custom alpha/flag, native world models')


if __name__=='__main__': main()
