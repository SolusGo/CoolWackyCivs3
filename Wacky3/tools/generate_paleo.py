def literal(value):
    if value is None: return 'NULL'
    if isinstance(value, int): return str(value)
    return "'"+str(value).replace("'", "''")+"'"


def clone(table, parent, child, changes):
    changes = {'ID': None, 'Type': child, **changes}
    return (f'CREATE TEMP TABLE PALEO_Clone AS SELECT * FROM {quote(table)} WHERE Type={literal(parent)};\n'
            +'UPDATE PALEO_Clone SET '+','.join(quote(k)+'='+literal(v) for k,v in changes.items())+';\n'
            +f'INSERT INTO {quote(table)} SELECT * FROM PALEO_Clone;\nDROP TABLE PALEO_Clone;\n')


def companions(db, prefix, column, parent, child):
    result = ''
    for table in approved_companions(prefix, column):
        columns = [r[1] for r in db.execute('PRAGMA table_info('+quote(table)+')')]
        assignments = quote(column)+'='+literal(child)
        if 'ID' in columns: assignments += ',ID=NULL'
        result += (f'CREATE TEMP TABLE PALEO_Companion AS SELECT * FROM {quote(table)} WHERE {quote(column)}={literal(parent)};\n'
                   +f'UPDATE PALEO_Companion SET {assignments};\nINSERT INTO {quote(table)} SELECT * FROM PALEO_Companion;\nDROP TABLE PALEO_Companion;\n')
    return result


def write(kind, content):
    SQL.mkdir(parents=True, exist_ok=True)
    (SQL/f'PALEO_{kind}.sql').write_text('-- Generated by tools/generate_paleo.py.\n'+content,
                                       encoding='utf-8', newline='\n')


