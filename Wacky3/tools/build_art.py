"""Compile retained original PNGs into legacy RGBA8888 DDS + complete mip chains.

No image generation service is required to rebuild. Source PNGs remain editable.
DDS is uncompressed to preserve small-texture alpha and avoid DX10-only formats.
"""
from pathlib import Path
from PIL import Image, ImageDraw, ImageOps
import struct
ROOT=Path(__file__).resolve().parents[1]
ART=ROOT/'TheMinistryOfAlmost/Art'
SIZES=(256,128,80,64,48,45,32,24,16)

def dds(image, path, mipmaps=True):
    layers=[image.convert('RGBA')]
    while mipmaps and layers[-1].size != (1,1):
        last=layers[-1]; layers.append(last.resize((max(1,last.width//2),max(1,last.height//2)),Image.Resampling.LANCZOS))
    w,h=layers[0].size; count=len(layers)
    flags=0x100F | (0x20000 if count>1 else 0)
    header=[124,flags,h,w,w*4,0,count]+[0]*11
    # DDS_PIXELFORMAT: RGB | ALPHAPIXELS, 32-bit BGRA memory order.
    header += [32,0x41,0,32,0x00FF0000,0x0000FF00,0x000000FF,0xFF000000]
    header += [0x1000 | (0x400008 if count>1 else 0),0,0,0,0]
    path.write_bytes(b'DDS '+struct.pack('<31I',*header)+b''.join(im.tobytes('raw','BGRA') for im in layers))

def portrait(image):
    w,h=image.size
    crop=image.crop((int(w*.30),int(h*.18),int(w*.70),int(h*.71)))
    out=ImageOps.fit(crop,(1024,1024),Image.Resampling.LANCZOS).convert('RGBA')
    mask=Image.new('L',out.size); ImageDraw.Draw(mask).ellipse((36,36,988,988),fill=255)
    out.putalpha(mask)
    draw=ImageDraw.Draw(out); draw.ellipse((36,36,988,988),outline=(196,160,84,255),width=20)
    return out

def compile_art():
    images={name:Image.open(ART/'Sources'/f'{name}.png').convert('RGBA') for name in ['Leader','Dawn','Emblem','Unit','Academy']}
    masters={'Civ':images['Emblem'],'LeaderIcon':portrait(images['Leader']),'Unit':images['Unit'],'Academy':images['Academy']}
    # The alpha emblem is a crisp original glyph; it stays readable on the map.
    alpha=Image.new('RGBA',(1024,1024)); draw=ImageDraw.Draw(alpha)
    draw.ellipse((104,104,920,920),outline='white',width=44)
    for x in [360,580]:
        draw.rectangle((x,300,x+80,724),fill='white')
        draw.rectangle((x-35,280,x+115,325),fill='white')
        draw.rectangle((x-35,699,x+115,744),fill='white')
    alpha.save(ART/'Sources/Alpha.png'); masters['Alpha']=alpha
    declarations=[]
    for kind,master in masters.items():
        atlas={'Civ':'CWC3_CIV_ATLAS','LeaderIcon':'CWC3_LEADER_ATLAS','Unit':'CWC3_UNIT_ATLAS',
               'Academy':'CWC3_ACADEMY_ATLAS','Alpha':'CWC3_ALPHA_ATLAS'}[kind]
        for size in SIZES:
            file=f'CWC3_{kind}{size}.dds'
            dds(ImageOps.contain(master,(size,size),Image.Resampling.LANCZOS).resize((size,size),Image.Resampling.LANCZOS),ART/file)
            declarations.append(f" ('{atlas}',{size},'{file}',1,1)")
    dds(images['Dawn'].resize((1024,768),Image.Resampling.LANCZOS),ART/'CWC3_Dawn.dds',False)
    dds(images['Leader'].resize((1600,1200),Image.Resampling.LANCZOS),ART/'CWC3_Leader.dds',False)
    # Fictional civilization: an illustrated capital detail replaces a false historical map.
    dds(ImageOps.fit(images['Dawn'],(360,412),Image.Resampling.LANCZOS,centering=(.5,.5)),ART/'CWC3_Map.dds',False)
    (ART/'CWC3_LeaderScene.xml').write_text('<?xml version="1.0" encoding="utf-8"?>\n<LeaderScene FallbackImage="CWC3_Leader.dds" />\n',encoding='utf-8',newline='\n')
    (ROOT/'TheMinistryOfAlmost/SQL/Ministry_Art.sql').write_text('-- Generated by tools/build_art.py.\nINSERT INTO IconTextureAtlases(Atlas,IconSize,Filename,IconsPerRow,IconsPerColumn) VALUES\n'+',\n'.join(declarations)+';\n',encoding='utf-8',newline='\n')
    sheet=Image.new('RGB',(1280,620),(20,28,42)); draw=ImageDraw.Draw(sheet)
    for i,kind in enumerate(['Civ','LeaderIcon','Unit','Academy','Alpha']):
        icon=Image.open(ART/f'CWC3_{kind}256.dds')
        sheet.paste(icon,(i*256,25),icon); draw.text((i*256+10,5),kind,fill='white')
    for kind,x in [('Dawn',15),('Leader',500)]:
        illustration=Image.open(ART/f'CWC3_{kind}.dds'); illustration.thumbnail((460,300))
        sheet.paste(illustration,(x,300))
    sheet.save(ART/'Sources/ArtReview.png')
    print(f'Compiled {len(declarations)+3} legacy DDS textures; 45 icon textures have full mip chains')
if __name__=='__main__': compile_art()
