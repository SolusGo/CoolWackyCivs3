SQL = Path(os.environ.get('CWC3_SQL_ROOT', ROOT))/'TheMinistryOfAlmost/SQL'
SQL.mkdir(parents=True, exist_ok=True)
DB = schema_database()

def literal(value):
    if value is None: return 'NULL'
    if isinstance(value, int): return str(value)
    return "'"+str(value).replace("'", "''")+"'"

def clone(table, old, new, changes):
    changes = {'ID':None, 'Type':new, **changes}
    return (f'CREATE TEMP TABLE CWC3_Clone AS SELECT * FROM {quote(table)} WHERE Type={literal(old)};\n'
        +'UPDATE CWC3_Clone SET '+','.join(quote(k)+'='+literal(v) for k,v in changes.items())+';\n'
        +f'INSERT INTO {quote(table)} SELECT * FROM CWC3_Clone;\nDROP TABLE CWC3_Clone;\n')

def companions(prefix, column, old, new):
    result = ''
    for table in approved_companions(prefix, column):
        cols = [r[1] for r in DB.execute('PRAGMA table_info('+quote(table)+')')]
        if column not in cols: continue
        # Companion tables ordinarily have no ID; retain auto-increment behavior if present.
        assignments = quote(column)+'='+literal(new)
        if 'ID' in cols: assignments += ',ID=NULL'
        result += (f'CREATE TEMP TABLE CWC3_Companion AS SELECT * FROM {quote(table)} WHERE {quote(column)}={literal(old)};\n'
            +f'UPDATE CWC3_Companion SET {assignments};\nINSERT INTO {quote(table)} SELECT * FROM CWC3_Companion;\nDROP TABLE CWC3_Companion;\n')
    return result

