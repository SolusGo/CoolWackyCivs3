"""Compile original Covenant PNG masters to the pack's legacy RGBA DDS format."""
import json
from PIL import Image, ImageDraw, ImageOps
from baseline import ROOT
from build_art import dds, SIZES

ART = ROOT/'TheCandlekeepersCovenant/Art'
def main():
    leader = Image.open(ART/'Sources/Leader.png').convert('RGBA')
    emblem = Image.open(ART/'Sources/Emblem.png').convert('RGBA')
    portrait = ImageOps.fit(leader,(1024,1024),Image.Resampling.LANCZOS,centering=(.5,.25))
    mask=Image.new('L',(1024,1024)); ImageDraw.Draw(mask).ellipse((30,30,994,994),fill=255)
    portrait.putalpha(mask)
    ImageDraw.Draw(portrait).ellipse((30,30,994,994),outline=(219,175,77,255),width=18)
    # Original code-native monochrome candle glyph for map flags.
    alpha=Image.new('RGBA',(1024,1024)); d=ImageDraw.Draw(alpha)
    d.ellipse((100,100,924,924),outline='white',width=55)
    d.rectangle((420,440,604,770),fill='white')
    d.ellipse((420,410,604,475),fill='white')
    d.polygon([(512,225),(445,345),(448,395),(512,425),(578,387),(575,330)],fill='white')
    d.line((512,415,512,450),fill='white',width=18)
    d.line((340,780,684,780),fill='white',width=40)
    alpha.save(ART/'Sources/Alpha.png')
    declarations=[]
    for kind,master in [('Civ',emblem),('Leader',portrait),('Alpha',alpha)]:
        for size in SIZES:
            name=f'CWC3_Covenant_{kind}{size}.dds'
            dds(master.resize((size,size),Image.Resampling.LANCZOS),ART/name)
            declarations.append(f" ('CWC3_COVENANT_{kind.upper()}_ATLAS',{size},'{name}',1,1)")
    dds(ImageOps.fit(leader,(1600,1200),Image.Resampling.LANCZOS),ART/'CWC3_Covenant_Leader.dds',False)
    dds(ImageOps.fit(leader,(1024,768),Image.Resampling.LANCZOS),ART/'CWC3_Covenant_Dawn.dds',False)
    dds(ImageOps.fit(emblem,(360,412),Image.Resampling.LANCZOS),ART/'CWC3_Covenant_Map.dds',False)
    (ART/'CWC3_Covenant_LeaderScene.xml').write_text('<?xml version="1.0" encoding="utf-8"?>\n<LeaderScene FallbackImage="CWC3_Covenant_Leader.dds" />\n',encoding='utf-8',newline='\n')
    sql=ROOT/'TheCandlekeepersCovenant/SQL/Covenant_Art.sql'
    sql.parent.mkdir(parents=True,exist_ok=True)
    sql.write_text('-- Generated by tools/build_covenant_art.py.\nINSERT INTO IconTextureAtlases(Atlas,IconSize,Filename,IconsPerRow,IconsPerColumn) VALUES\n'+',\n'.join(declarations)+';\n',encoding='utf-8',newline='\n')
    review=Image.new('RGB',(1100,650),(10,18,38))
    for x,kind in [(20,'Civ'),(300,'Leader'),(580,'Alpha')]:
        icon=Image.open(ART/f'CWC3_Covenant_{kind}256.dds'); review.paste(icon,(x,15),icon)
    scene=Image.open(ART/'CWC3_Covenant_Leader.dds'); scene.thumbnail((480,350)); review.paste(scene,(20,290))
    scene=Image.open(ART/'CWC3_Covenant_Dawn.dds'); scene.thumbnail((480,350)); review.paste(scene,(550,290))
    review.save(ART/'Sources/ArtReview.png')
    print('Compiled Covenant: 30 DDS assets; native Pikeman/Temple portraits and world art inherited')

if __name__=='__main__': main()
