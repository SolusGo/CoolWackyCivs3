def literal(value):
    if value is None: return 'NULL'
    if isinstance(value, int): return str(value)
    return "'"+str(value).replace("'", "''")+"'"


def clone(table, old, new, changes):
    changes = {'ID': None, 'Type': new, **changes}
    return (f'CREATE TEMP TABLE CWC3_TimetableClone AS SELECT * FROM {quote(table)} WHERE Type={literal(old)};\n'
            +'UPDATE CWC3_TimetableClone SET '+','.join(quote(k)+'='+literal(v) for k,v in changes.items())+';\n'
            +f'INSERT INTO {quote(table)} SELECT * FROM CWC3_TimetableClone;\nDROP TABLE CWC3_TimetableClone;\n')


def companions(db, prefix, column, old, new):
    result = ''
    for table in approved_companions(prefix, column):
        columns = [r[1] for r in db.execute('PRAGMA table_info('+quote(table)+')')]
        assignments = quote(column)+'='+literal(new)
        if 'ID' in columns: assignments += ',ID=NULL'
        result += (f'CREATE TEMP TABLE CWC3_TimetableCompanion AS SELECT * FROM {quote(table)} WHERE {quote(column)}={literal(old)};\n'
                   +f'UPDATE CWC3_TimetableCompanion SET {assignments};\nINSERT INTO {quote(table)} SELECT * FROM CWC3_TimetableCompanion;\nDROP TABLE CWC3_TimetableCompanion;\n')
    return result


def write(kind, content):
    SQL.mkdir(parents=True, exist_ok=True)
    (SQL/f'Timetable_{kind}.sql').write_text('-- Generated by tools/generate_timetable.py.\n'+content,
                                           encoding='utf-8', newline='\n')


