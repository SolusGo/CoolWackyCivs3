"""Pin CP151 UI and hide only the internal Summer ancestry marker.

CP151 declares ShowInUnitPanel but its shipped panels do not read it. Two narrow
VFS overrides preserve all shipped behavior except this marker's icon. Sources
are the user's installed CP151; no unrelated UI framework is introduced.
"""
import hashlib
import os
import re
from pathlib import Path
from baseline import ROOT, USER

SOURCES = [
    ('LUA/UnitPanel.lua','96b37d09f26254b8475151272a7b36a4b63fd4b1fe7110c9fd8fb88044ab6e4a',
     'if (unit:IsHasPromotion(unitPromotionID) and not unit:IsTrade()) then',
     "if (unit:IsHasPromotion(unitPromotionID) and not unit:IsTrade() and unitPromotion.Type ~= 'PROMOTION_SUMMER_BROOD_LINEAGE') then"),
    ('Core Files/Overrides/EnemyUnitPanel.lua','aea05e732dcb44eef69013b3e15fc22b816ee6e4e2d685be95c4978c6a47812a',
     'if pUnit:IsHasPromotion(ePromotion) then',
     "if pUnit:IsHasPromotion(ePromotion) and pPromotion.Type ~= 'PROMOTION_SUMMER_BROOD_LINEAGE' then"),
]


def generated():
    cp=Path(os.environ.get('CWC3_CP_DIR',USER/'MODS/(1) Community Patch'))
    result={}
    for relative,digest,old,new in SOURCES:
        source=(cp/relative).read_bytes()
        assert hashlib.sha256(source).hexdigest()==digest,('CP151 UI source changed',relative)
        text=source.decode('utf-8-sig').replace('\r\n','\n')
        # Canonical source formatting; Lua tokens and string contents are unchanged.
        text='\n'.join(re.sub(r'^[ \t]+',lambda m:m[0].expandtabs(4),line.rstrip()) for line in text.splitlines())+'\n'
        assert text.count(old)==1
        result[Path(relative).name]='-- Generated by tools/generate_summer_ui.py from pinned CP151 '+relative+'.\n'+text.replace(old,new)
    return result


def main():
    dest=ROOT/'TheSeventeenthSummer/UI'; dest.mkdir(exist_ok=True)
    for name,text in generated().items(): (dest/name).write_text(text,encoding='utf-8',newline='\n')
    print('Generated two CP151 panel overrides: only the hidden lineage icon is filtered')


if __name__=='__main__': main()
