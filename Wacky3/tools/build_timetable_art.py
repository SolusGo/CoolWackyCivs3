"""Compile retained original Timetable PNGs using the pack's legacy DDS writer."""
from PIL import Image, ImageDraw, ImageOps
from math import cos, sin, pi
from baseline import ROOT
from build_art import dds, SIZES

ART = ROOT/'ThePerpetualTimetable/Art'


def compile_art():
    (ROOT/'ThePerpetualTimetable/SQL').mkdir(parents=True, exist_ok=True)
    images = {name: Image.open(ART/'Sources'/f'{name}.png').convert('RGBA')
              for name in ['Emblem', 'Leader', 'Dawn', 'Unit', 'Office']}
    leader = ImageOps.fit(images['Leader'], (1024,1024), Image.Resampling.LANCZOS, centering=(.5,.35))
    mask = Image.new('L', (1024,1024))
    ImageDraw.Draw(mask).ellipse((36,36,988,988), fill=255)
    leader.putalpha(mask)
    ImageDraw.Draw(leader).ellipse((36,36,988,988), outline=(196,160,84,255), width=20)
    # Simple original monochrome map glyph: wheel, spokes and clock hands.
    alpha = Image.new('RGBA', (1024,1024))
    draw = ImageDraw.Draw(alpha)
    draw.ellipse((112,112,912,912), outline='white', width=60)
    draw.ellipse((188,188,836,836), outline='white', width=24)
    for i in range(12):
        angle = i*pi/6
        draw.line((512+270*cos(angle),512+270*sin(angle),512+370*cos(angle),512+370*sin(angle)), fill='white', width=32)
    draw.line((512,310,512,512,680,600), fill='white', width=42)
    draw.ellipse((477,477,547,547), fill='white')
    alpha.save(ART/'Sources/Alpha.png')
    masters = {'Civ':images['Emblem'], 'Leader':leader, 'Unit':images['Unit'], 'Office':images['Office'], 'Alpha':alpha}
    declarations = []
    for kind, master in masters.items():
        for size in SIZES:
            name = f'CWC3_Timetable_{kind}{size}.dds'
            dds(master.resize((size,size), Image.Resampling.LANCZOS), ART/name)
            declarations.append(f" ('CWC3_TIMETABLE_{kind.upper()}_ATLAS',{size},'{name}',1,1)")
    dds(images['Dawn'].resize((1024,768), Image.Resampling.LANCZOS), ART/'CWC3_Timetable_Dawn.dds', False)
    dds(images['Leader'].resize((1600,1200), Image.Resampling.LANCZOS), ART/'CWC3_Timetable_Leader.dds', False)
    dds(ImageOps.fit(images['Dawn'], (360,412), Image.Resampling.LANCZOS), ART/'CWC3_Timetable_Map.dds', False)
    (ART/'CWC3_Timetable_LeaderScene.xml').write_text('<?xml version="1.0" encoding="utf-8"?>\n<LeaderScene FallbackImage="CWC3_Timetable_Leader.dds" />\n', encoding='utf-8', newline='\n')
    (ROOT/'ThePerpetualTimetable/SQL/Timetable_Art.sql').write_text('-- Generated by tools/build_timetable_art.py.\nINSERT INTO IconTextureAtlases(Atlas,IconSize,Filename,IconsPerRow,IconsPerColumn) VALUES\n'+',\n'.join(declarations)+';\n', encoding='utf-8', newline='\n')
    review = Image.new('RGB', (1280,640), (16,24,40))
    draw = ImageDraw.Draw(review)
    for i,kind in enumerate(masters):
        icon = Image.open(ART/f'CWC3_Timetable_{kind}256.dds')
        review.paste(icon, (i*256,25), icon)
        draw.text((i*256+10,5), kind, fill='white')
    for kind,x in [('Dawn',15),('Leader',550)]:
        illustration = Image.open(ART/f'CWC3_Timetable_{kind}.dds')
        illustration.thumbnail((500,330))
        review.paste(illustration, (x,300))
    review.save(ART/'Sources/ArtReview.png')
    print('Compiled Timetable: 48 legacy RGBA DDS textures, 45 complete icon mip chains')


if __name__ == '__main__': compile_art()
